const waitFor = async (predicate, label, timeout = 15000) => {
  const started = Date.now();
  while (Date.now() - started < timeout) { if (await predicate()) return; await new Promise(resolve => setTimeout(resolve, 100)); }
  if (diagnostics) console.error('Browser state:', JSON.stringify(await diagnostics()));
  throw new Error('Timed out: ' + label);
};
