const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const http = require('node:http');
const { closeApp } = require('./app-helpers');

const root = path.resolve(__dirname, '..'), profile = fs.mkdtempSync(path.join(os.tmpdir(), 'luna-privacy-smoke-'));
const artifacts = path.join(root, 'artifacts'); fs.mkdirSync(artifacts, { recursive: true });
let application, page;
const errors = [];
const server = http.createServer((request, response) => {
  response.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
  response.end('<!doctype html><title>Privacy Test Page</title><h1>Privacy test</h1><script>localStorage.setItem("luna_privacy","saved");</script>');
});
const waitFor = async (predicate, label) => { const start = Date.now(); while (Date.now() - start < 15000) { if (await predicate()) return; await new Promise(resolve => setTimeout(resolve, 50)); } throw new Error('Timed out: ' + label); };
async function run() {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = 'http://127.0.0.1:' + server.address().port;
  const env = { ...process.env, LUNA_USER_DATA: profile }; delete env.ELECTRON_RUN_AS_NODE;
  const options = { executablePath: process.env.LUNA_EXECUTABLE || require('electron'), args: process.env.LUNA_EXECUTABLE ? ['--disable-gpu'] : [root, '--disable-gpu'], env, timeout: 30000 };
  async function launch() {
    application = await electron.launch(options); page = await application.firstWindow();
    page.on('pageerror', error => errors.push(error.message)); await page.waitForSelector('.tab.selected');
    await application.evaluate(({ dialog }) => { dialog.showMessageBox = dialog.showMessageBoxSync = () => { throw new Error('A native confirmation dialog was used'); }; });
  }
  const state = () => page.evaluate(() => window.browser.command('state'));
  const command = (action, payload) => page.evaluate(({ action, payload }) => window.browser.command(action, payload), { action, payload });
  const cookies = () => application.evaluate(({ session }) => session.fromPartition('persist:luma-web').cookies.get({}));
  const screenshot = async name => { await page.waitForTimeout(150); await page.screenshot({ path: path.join(artifacts, name) }); };
  await launch();
  const storagePath = await application.evaluate(async ({ session }, base) => {
    const browserSession = session.fromPartition('persist:luma-web');
    await browserSession.cookies.set({ url: base, name: 'old_cookie', value: 'old-value', expirationDate: Date.now() / 1000 + 86400 });
    await browserSession.cookies.flushStore(); return browserSession.getStoragePath();
  }, base);
  await closeApp(application, page); application = null;
  const now = Date.now(), old = now - 7200000;
  const { DatabaseSync } = require('node:sqlite');
  const database = new DatabaseSync(path.join(storagePath, 'Network', 'Cookies'));
  database.prepare('UPDATE cookies SET creation_utc = ? WHERE name = ?').run(BigInt(old + 11644473600000) * 1000n, 'old_cookie'); database.close();
  const file = path.join(profile, 'browser-data.json'), data = JSON.parse(fs.readFileSync(file, 'utf8'));
  data.history = [{ url: base + '/old', title: 'Old visit', time: old }, { url: base + '/recent', title: 'Recent visit', time: now - 60000 }];
  data.bookmarks = [{ url: base + '/saved', title: 'Keep bookmark', time: old }];
  data.cookieTimes = Object.fromEntries(Object.keys(data.cookieTimes).map(key => [key, old]));
  data.siteSettings = { [base]: { time: now - 60000, zoomFactor: 1.5 } };
  data.settings.theme = 'dark'; fs.writeFileSync(file, JSON.stringify(data));
  const downloadedFile = path.join(profile, 'keep-download.txt'); fs.writeFileSync(downloadedFile, 'Keep the downloaded file');
  const ended = time => ({ id: crypto.randomUUID(), url: base + '/download.txt', name: 'keep-download.txt', file: downloadedFile, status: 'completed', mode: 'single', threads: [], total: 24, received: 24, createdAt: time, requestedThreads: 1, speedLimit: 0, completion: 'none', icon: '', validator: null });
  const recentDownload = ended(now - 60000), oldDownload = ended(old);
  const pausedDownload = { ...ended(now - 60000), id: crypto.randomUUID(), file: path.join(profile, 'pending.txt'), status: 'paused', mode: 'checking', received: 0 };
  fs.writeFileSync(path.join(profile, 'download-jobs.json'), JSON.stringify([recentDownload, oldDownload, pausedDownload]));
  await launch(); await command('navigate', base + '/recent');
  await waitFor(async () => (await state()).history.some(entry => entry.url === base + '/recent' && entry.title === 'Privacy Test Page'), 'website loaded and recorded');
  await application.evaluate(({ session }, base) => session.fromPartition('persist:luma-web').cookies.set({ url: base, name: 'new_cookie', value: 'new-value', expirationDate: Date.now() / 1000 + 86400 }), base);
  const stats = await command('browsing-data-stats', { range: 'hour' });
  assert.equal(stats.history, 1); assert.equal(stats.cookies, 1, 'native creation time excludes the old cookie'); assert.equal(stats.downloads, 1);
  await command('clear-browsing-data'); await page.waitForSelector('#clear-data-dialog[open]');
  await waitFor(async () => !await page.locator('#clear-data-submit').isDisabled(), 'data counts loaded');
  assert.equal(await page.locator('[data-clear-type]').count(), 6);
  assert.equal(await page.locator('[data-clear-type="passwords"]').isChecked(), false, 'password deletion requires explicit selection');
  assert.equal(await page.locator('.clear-data-option input:disabled').count(), 2);
  await screenshot('clear-browsing-data.png');
  await page.locator('#clear-data-cancel').click();
  assert.equal((await state()).history.length, 2); assert.equal((await cookies()).length, 2);
  await command('clear-browsing-data'); await page.waitForSelector('#clear-data-dialog[open]');
  await page.locator('[data-clear-type="cache"]').uncheck();
  await waitFor(async () => !await page.locator('#clear-data-submit').isDisabled(), 'data ready');
  await page.locator('#clear-data-submit').click(); await page.waitForSelector('#clear-data-dialog:not([open])', { state: 'attached' });
  const after = await state(); assert.equal(after.history.length, 1); assert.equal(after.history[0].url, base + '/old');
  assert.equal(after.bookmarks.length, 1); assert.equal(after.downloads.some(job => job.id === recentDownload.id), false);
  assert.equal(after.downloads.some(job => job.id === oldDownload.id), true); assert.equal(after.downloads.some(job => job.id === pausedDownload.id), true);
  assert.equal(fs.readFileSync(downloadedFile, 'utf8'), 'Keep the downloaded file');
  assert.deepEqual((await cookies()).map(cookie => cookie.name), ['old_cookie']);
  const localStorage = await application.evaluate(({ webContents }, base) => webContents.getAllWebContents().find(web => web.getURL().startsWith(base)).executeJavaScript('localStorage.getItem("luna_privacy")'), base);
  assert.equal(localStorage, null);
  await command('clear-browsing-data'); await page.waitForSelector('#clear-data-dialog[open]');
  await page.locator('#clear-data-more').selectOption('all');
  for (const type of ['cache', 'downloads']) await page.locator(`[data-clear-type="${type}"]`).uncheck();
  await page.locator('[data-clear-type="siteSettings"]').check();
  await waitFor(async () => !await page.locator('#clear-data-submit').isDisabled(), 'all-time counts');
  await page.locator('#clear-data-submit').click(); await page.waitForSelector('#clear-data-dialog:not([open])', { state: 'attached' });
  assert.equal((await cookies()).length, 0); assert.equal((await state()).history.length, 0); assert.equal((await state()).tabs[0].zoom, 100);
  assert.equal((await state()).bookmarks.length, 1);
  const reset = command('reset-settings'); await page.waitForSelector('#confirmation-dialog[open]');
  assert.equal(await page.locator('#confirmation-dialog').getAttribute('data-kind'), 'reset-settings');
  await page.locator('#confirmation-cancel').click(); await reset; assert.equal((await state()).settings.theme, 'dark');
  const resetAgain = command('reset-settings'); await page.waitForSelector('#confirmation-dialog[open]');
  await page.locator('#confirmation-accept').click(); await resetAgain; assert.equal((await state()).settings.theme, 'light');
  await command('update-settings', { theme: 'dark' });
  const first = (await state()).activeId;
  await command('new-tab', base + '/recent'); const second = (await state()).activeId;
  await command('settings'); await command('new-tab'); await command('activate', second);
  const sessionURLs = (await state()).tabs.map(tab => tab.url), selectedIndex = (await state()).tabs.findIndex(tab => tab.id === second);
  assert.equal(sessionURLs.length, 4);
  await page.locator('#close-window').click(); await page.waitForSelector('#confirmation-dialog[open]');
  assert.equal(await page.locator('#confirmation-dialog').getAttribute('data-kind'), 'close-browser');
  assert.equal(await page.locator('.confirmation-tab').count(), 4);
  assert.equal(await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().length), 1, 'confirmation lives in the browser UI');
  await screenshot('close-session-confirmation.png');
  await page.locator('#confirmation-cancel').click();
  assert.deepEqual((await state()).tabs.map(tab => tab.url), sessionURLs); assert.equal((await state()).activeId, second);
  await closeApp(application, page, true); application = null;
  await launch();
  await waitFor(async () => (await state()).tabs.length === 4, 'all session tabs restored');
  assert.deepEqual((await state()).tabs.map(tab => tab.url), sessionURLs);
  const restoredSession = await state();
  assert.equal(restoredSession.tabs.findIndex(tab => tab.id === restoredSession.activeId), selectedIndex);
  assert.equal((await state()).settings.startup, 'restore');
  await closeApp(application, page, false); application = null;
  await launch(); assert.equal((await state()).tabs.length, 1); assert.equal((await state()).tabs[0].url, 'luna://newtab');
  assert.equal((await state()).settings.startup, 'restore', 'one-time close choice leaves the default preference intact');
  assert.equal(fs.readFileSync(downloadedFile, 'utf8'), 'Keep the downloaded file');
  assert.deepEqual(errors, []);
  await closeApp(application, page, false); application = null;
  console.log('PASS: browser-only confirmations, cancel protection, precise history/cookie/download time ranges, website storage clearing, download-file protection, active-job protection, site settings reset, full multi-tab restoration, active tab and internal pages, one-time no-restore choice, default preference preserved.');
  fs.writeFileSync(path.join(artifacts, 'privacy-result.json'), JSON.stringify({ passed: true, testedAt: new Date().toISOString() }, null, 2));
}
run().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (application) await closeApp(application, page, false).catch(() => application.process().kill());
  await new Promise(resolve => server.close(resolve)); fs.rmSync(profile, { recursive: true, force: true });
});
